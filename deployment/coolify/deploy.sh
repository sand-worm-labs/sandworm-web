#!/usr/bin/env bash
# Deploys Sandworm to Coolify and makes its env files. Replaces
# scripts/start-prod.sh and the env scripts it ran.
#
#   deploy.sh secrets staging                fresh random secrets → sandworm-staging-secrets.env
#   deploy.sh envs <env>                     list every setting (names only)
#   deploy.sh envs <env> --write             write the env files (see below) to look at or paste
#   deploy.sh envs <env> --apply             send them to Coolify and GitHub
#   deploy.sh <env>                          build images in CI, then deploy
#   deploy.sh <env> --no-build               redeploy the current images
#
# <env> is staging or production.
#
# Where the settings come from, later ones winning:
#   1. the root env files you already have: sandworm-{api,postgres,mcp,ai,web}.env
#      (for staging, a sandworm-staging-<app>.env replaces each when it exists)
#   2. sandworm-<env>-secrets.env, from `deploy.sh secrets`
#   3. everything domain-based (URLs, cookie domain, MCP resource...), worked out
#      from the environment, as setup-domain-envs.sh did
# Runtime settings go to Coolify. NEXT_PUBLIC_* go to the GitHub environment,
# because CI bakes them into the images.
#
# --write makes sandworm-stack-<env>.env (Coolify) and
# sandworm-stack-<env>.build.env (GitHub), owner-only, git-ignored.
#
# Needs curl, jq and gh (signed in). Coolify access, for --apply and deploys,
# comes from ~/.config/sandworm/coolify-<env>.env, outside the repo:
#   COOLIFY_URL=https://coolify.example.com
#   COOLIFY_TOKEN=...            (Keys & Tokens: write + deploy)
#   COOLIFY_RESOURCE_UUID=...    (the stack resource)
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"

die() { echo "error: $*" >&2; exit 1; }
log() { printf '\033[1m▶ %s\033[0m\n' "$*"; }
usage() { sed -n '2,31p' "$0"; exit 2; }

for tool in curl jq gh openssl; do command -v "$tool" >/dev/null || die "needs $tool"; done

# ── Environments ─────────────────────────────────────────────────────────────
set_domains() {
  case "$1" in
    staging)    BASE=staging.sandwormlab.xyz; WWW=staging.sandwormlab.xyz; BRANCH_DEFAULT="$(git -C "$ROOT_DIR" branch --show-current 2>/dev/null || true)" ;;
    production) BASE=sandwormlab.xyz;         WWW=www.sandwormlab.xyz;     BRANCH_DEFAULT=main ;;
    *) usage ;;
  esac
  APP="https://app.$BASE"
  TERMINAL="https://terminal.$BASE"
  MCP="https://mcp.$BASE"
  LANDING="https://$BASE"
  WS="wss://app.$BASE"
}

load_coolify() {
  local file="${HOME}/.config/sandworm/coolify-$1.env"
  if [ -r "$file" ]; then set -a; . "$file"; set +a; fi
  : "${COOLIFY_URL:?set in $file}" "${COOLIFY_TOKEN:?set in $file}" "${COOLIFY_RESOURCE_UUID:?set in $file}"
  COOLIFY_URL="${COOLIFY_URL%/}"
}

coolify() {
  local method="$1" path="$2"; shift 2
  curl -fsS -X "$method" -H "Authorization: Bearer $COOLIFY_TOKEN" -H 'Content-Type: application/json' \
    "$COOLIFY_URL/api/v1$path" "$@"
}

# ── secrets ──────────────────────────────────────────────────────────────────
# Generated per environment. Not ENVIRONMENT_VARIABLES_ENCRYPTION_KEY: it
# decrypts what users saved, so it stays the one in sandworm-api.env.
GENERATED=(AUTH_JWT_SECRET AUTH_REFRESH_SECRET AUTH_FORGOT_SECRET AUTH_CONFIRM_EMAIL_SECRET
           DATABASE_PASSWORD JUPYTER_TOKEN AI_HANDSHAKE_TOKEN MCP_OAUTH_INTROSPECT_KEY QDRANT_API_KEY)

cmd_secrets() {
  local env="${1:-}"
  [ "$env" = staging ] || die "only for staging: new production secrets would sign everyone out and lock the old database"
  local file="$ROOT_DIR/sandworm-$env-secrets.env"
  [ -e "$file" ] && die "$(basename "$file") exists; delete it first if you really want new secrets"
  ( umask 077
    { echo "# Generated by deploy.sh secrets $env on $(date -u +%F). Keep it out of git."
      for k in "${GENERATED[@]}"; do echo "$k=$(openssl rand -hex 32)"; done
    } > "$file" )
  echo "Wrote $(basename "$file") (${#GENERATED[@]} secrets). Next: $0 envs $env --write"
}

# ── envs ─────────────────────────────────────────────────────────────────────
# Never sent: the compose file points these at the stack's own services, or
# nothing reads them any more.
SKIP='^(DATABASE_HOST|DATABASE_PORT|DATABASE_TYPE|APP_PORT|JUPYTER_HOST|JUPYTER_PORT|JUPYTER_PROTOCOL|AI_SERVICE_URL|NEST_BASE_URL|REDIS_URL|QDRANT_URL|MCP_URL|INTERNAL_API_URL|PORT|NODE_ENV|API_URL|LOGDY_[A-Z_]+|NEXT_PUBLIC_URL|MCP_RESOURCE_URL|MPP_[A-Z_]+|QUERY_PRICE)$'

declare -A RUNTIME=() BUILD=() SOURCE=()

# Reads KEY=VALUE lines. Without "override", a key two files disagree on is an error.
read_env_file() {
  local file="$1" mode="${2:-}" line key value seen
  [ -r "$file" ] || return 0
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%$'\r'}"
    [[ "$line" =~ ^[[:space:]]*(#|$) ]] && continue
    [[ "$line" =~ ^[[:space:]]*(export[[:space:]]+)?([A-Za-z_][A-Za-z0-9_]*)=(.*)$ ]] || { echo "  skipped a line in $(basename "$file") that isn't KEY=VALUE" >&2; continue; }
    key="${BASH_REMATCH[2]}"; value="${BASH_REMATCH[3]}"
    # One pair of surrounding quotes is syntax, not value.
    if [[ "$value" =~ ^\"(.*)\"$ ]] || [[ "$value" =~ ^\'(.*)\'$ ]]; then value="${BASH_REMATCH[1]}"; fi
    [ -n "$value" ] || continue
    [[ "$key" =~ $SKIP ]] && continue
    if [[ "$key" =~ ^(NEXT_PUBLIC_|PUBLIC_) ]]; then seen="${BUILD[$key]-}"; else seen="${RUNTIME[$key]-}"; fi
    if [ "$mode" != override ] && [ -n "$seen" ] && [ "$seen" != "$value" ]; then
      die "$key differs between ${SOURCE[$key]} and $(basename "$file"): make them agree"
    fi
    if [[ "$key" =~ ^(NEXT_PUBLIC_|PUBLIC_) ]]; then BUILD[$key]="$value"; else RUNTIME[$key]="$value"; fi
    SOURCE[$key]="$(basename "$file")"
  done < "$file"
}

collect_envs() {
  local env="$1" app file k
  for app in api postgres mcp ai web; do
    file="$ROOT_DIR/sandworm-$app.env"
    [ "$env" = staging ] && [ -r "$ROOT_DIR/sandworm-staging-$app.env" ] && file="$ROOT_DIR/sandworm-staging-$app.env"
    read_env_file "$file"
  done
  read_env_file "$ROOT_DIR/sandworm-$env-secrets.env" override

  declare -A derived=(
    [IMAGE_TAG]="$env"
    [APP_HOST]="app.$BASE" [TERMINAL_HOST]="terminal.$BASE" [MCP_HOST]="mcp.$BASE"
    [LANDING_HOST]="$BASE" [LANDING_WWW_HOST]="$WWW"
    [APP_URL]="$APP" [APP_CORS_ORIGIN]="$APP" [FRONTEND_DOMAIN]="$APP" [BACKEND_DOMAIN]="$APP"
    [AUTH_COOKIE_DOMAIN]=".$BASE"
    [MCP_OAUTH_RESOURCE]="$MCP/mcp" [MCP_PUBLIC_URL]="$MCP/mcp"
    [AUTH_SERVER_URL]="$APP" [WEB_URL]="$APP" [REDIRECT_URI]="$APP/workspace/"
  )
  for k in "${!derived[@]}"; do RUNTIME[$k]="${derived[$k]}"; SOURCE[$k]="domain"; done
  declare -A build_derived=(
    [NEXT_PUBLIC_PUBLIC_URL]="$APP" [NEXT_PUBLIC_LANDING_URL]="$LANDING"
    [NEXT_PUBLIC_API_URL]="$APP/api" [NEXT_PUBLIC_API_WS_URL]="$WS" [NEXT_PUBLIC_YJS_WS_URL]="$WS"
    [NEXT_PUBLIC_WEB_APP_URL]="$APP" [NEXT_PUBLIC_TERMINAL_URL]="$TERMINAL" [PUBLIC_APP_URL]="$APP"
    [NEXT_PUBLIC_REDIRECT_URI]="$APP/auth/callback/github"
  )
  for k in "${!build_derived[@]}"; do BUILD[$k]="${build_derived[$k]}"; SOURCE[$k]="domain"; done

  local required=(DATABASE_USERNAME DATABASE_PASSWORD DATABASE_NAME JUPYTER_TOKEN AI_HANDSHAKE_TOKEN
                  MCP_OAUTH_INTROSPECT_KEY OPENROUTER_EMBEDDING_KEY AUTH_JWT_SECRET ENVIRONMENT_VARIABLES_ENCRYPTION_KEY)
  local missing=()
  for k in "${required[@]}"; do [ -n "${RUNTIME[$k]:-}" ] || missing+=("$k"); done
  [ ${#missing[@]} -eq 0 ] || die "missing: ${missing[*]}"

  if [ "$env" = staging ] && [ "${SOURCE[AUTH_JWT_SECRET]}" = sandworm-api.env ]; then
    echo "warning: staging would sign tokens with production's secrets, which production would accept." >&2
    echo "         Run: $0 secrets staging" >&2
  fi
}

write_env() {
  local file="$1" title="$2"; local -n map="$3"
  ( umask 077
    { echo "# $title. Made by deploy.sh on $(date -u +%F); keep it out of git."
      for k in $(printf '%s\n' "${!map[@]}" | sort); do printf '%s=%s\n' "$k" "${map[$k]}"; done
    } > "$file" )
  echo "  wrote $(basename "$file") (${#map[@]})"
}

cmd_envs() {
  local env="${1:-}" apply=false write=false
  shift || true
  for arg in "$@"; do
    case "$arg" in --apply) apply=true ;; --write) write=true ;; *) usage ;; esac
  done
  set_domains "$env"
  collect_envs "$env"

  local k
  log "Coolify settings for $env (${#RUNTIME[@]})"
  for k in $(printf '%s\n' "${!RUNTIME[@]}" | sort); do printf '  %-40s from %s\n' "$k" "${SOURCE[$k]}"; done
  log "GitHub build settings for $env (${#BUILD[@]})"
  for k in $(printf '%s\n' "${!BUILD[@]}" | sort); do printf '  %-40s from %s\n' "$k" "${SOURCE[$k]}"; done

  if [ "$write" = true ]; then
    log "Writing env files"
    write_env "$ROOT_DIR/sandworm-stack-$env.env" "Coolify settings for $env" RUNTIME
    write_env "$ROOT_DIR/sandworm-stack-$env.build.env" "GitHub build variables for $env" BUILD
  fi
  if [ "$apply" != true ]; then
    [ "$write" = true ] || { echo; echo "Nothing changed. --write makes the files, --apply sends them."; }
    return
  fi

  load_coolify "$env"
  log "Setting Coolify env vars"
  # is_literal: Coolify stores the value as is, so a $ in a secret stays a $.
  local payload
  payload="$(for k in "${!RUNTIME[@]}"; do jq -n --arg k "$k" --arg v "${RUNTIME[$k]}" '{key:$k, value:$v, is_preview:false, is_literal:true}'; done | jq -s '{data: .}')"
  coolify PATCH "/applications/$COOLIFY_RESOURCE_UUID/envs/bulk" --data "$payload" >/dev/null
  echo "  ${#RUNTIME[@]} set"

  log "Setting GitHub variables (environment: $env)"
  local repo
  repo="$(gh repo view --json nameWithOwner -q .nameWithOwner)"
  for k in "${!BUILD[@]}"; do gh variable set "$k" --env "$env" --body "${BUILD[$k]}" --repo "$repo" >/dev/null; done
  echo "  ${#BUILD[@]} set"
  echo; echo "Done. Deploy with: $0 $env"
}

# ── deploy ───────────────────────────────────────────────────────────────────
wait_for_coolify() {
  local deployment="$1" status
  log "Following Coolify deployment $deployment"
  while :; do
    status="$(coolify GET "/deployments/$deployment" | jq -r '.status')"
    case "$status" in
      finished) echo "  finished"; return 0 ;;
      failed|cancelled*) die "deployment $status: open it in Coolify for the log" ;;
      *) printf '  %s\n' "$status"; sleep 10 ;;
    esac
  done
}

cmd_deploy() {
  local env="$1" build=true ref=""
  shift
  set_domains "$env"
  while [ $# -gt 0 ]; do
    case "$1" in
      --no-build) build=false; shift ;;
      --ref) ref="$2"; shift 2 ;;
      *) usage ;;
    esac
  done
  ref="${ref:-$BRANCH_DEFAULT}"

  if [ "$build" = false ]; then
    load_coolify "$env"
    log "Redeploying $env with its current images"
    local deployment
    deployment="$(coolify GET "/deploy?uuid=$COOLIFY_RESOURCE_UUID&force=false" | jq -r '.deployments[0].deployment_uuid')"
    [ -n "$deployment" ] && [ "$deployment" != null ] || die "Coolify didn't start a deployment"
    wait_for_coolify "$deployment"
    return
  fi

  if [ "$env" = production ] && [ "$ref" != main ]; then
    die "production deploys from main (asked for $ref)"
  fi
  if [ -n "$(git -C "$ROOT_DIR" status --porcelain --untracked-files=no)" ]; then
    echo "note: you have uncommitted changes; CI builds what is pushed to $ref" >&2
  fi

  log "Building and deploying $env from $ref (workflow: images)"
  local before run
  before="$(gh run list --workflow images.yml --event workflow_dispatch --limit 1 --json databaseId -q '.[0].databaseId // 0')"
  gh workflow run images.yml --ref "$ref" -f environment="$env"
  for _ in $(seq 1 30); do
    run="$(gh run list --workflow images.yml --event workflow_dispatch --limit 1 --json databaseId -q '.[0].databaseId // 0')"
    [ "$run" != "$before" ] && break
    sleep 2
  done
  [ "$run" != "$before" ] || die "the workflow run didn't show up; check the Actions tab"
  gh run watch "$run" --exit-status
  echo; echo "✅ $env deployed: $APP"
}

case "${1:-}" in
  secrets) shift; cmd_secrets "$@" ;;
  envs) shift; cmd_envs "$@" ;;
  staging|production) cmd_deploy "$@" ;;
  *) usage ;;
esac
